# BEKLENEN ÇIKTI:
# Hoş geldin Burak
# Maceraya hazır mısın?

# Fonksiyona ikinci bir seviye parametresi ekle ve oyuncunun seviyesini de göster

def oyuncu_karsila(isim, seviye):
    print("Hoş Geldin,", isim)
    print("Seviyen:", seviye)
    print("MACERAYA HAZIR MISIN!")

oyuncu_karsila("Burak", 25)

oyuncu_karsila("Ahmet", 10)